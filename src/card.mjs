// The state card: what the agent gets at the start of a session instead of a hand-written STATE.md.
// Computed from the graph and git, without any model, so no one has to write a handoff. The view is the
// same card with every milestone in full, written to .ariadne/STATE.md for Read and grep.

import { isWork, makeGraph } from './graph.mjs'
import { words } from './i18n.mjs'
import { showRef } from './refs.mjs'

const say = words({
  en: {
    notFound: '(not found)', where: (path, status) => `You are in: ${path} (${status})`,
    lost: id => `You are in: ${id} (node not found in the graph)`, idle: 'You are in: no step started (ariadne start <id>)', left: what => `Left to do: ${what ?? '(not written)'}`,
    next: 'Next', none: 'none in the plan', waiting: 'Returns waiting', back: 'returns to', noWaiting: 'Returns waiting: none',
    because: 'why', loose: '## Outside the milestones', replacedBy: 'replaced by', deferredTo: 'deferred to',
    changed: '## Replaced decisions and deferrals', others: '## Other milestones',
    allSteps: 'Every step, one line each: .ariadne/STATE.md',
    title: full => `# Work state (${full ? 'view generated by ariadne: do not edit by hand' : 'card generated by ariadne'})`,
    cut: '… (cut: .ariadne/STATE.md)',
    comments: '## Comments to read', reply: id => `answer: ariadne answer ${id} "…"`,
    decisions: '## Open decisions', risks: '## Open risks', on: 'on', kind: { decision: 'decision', risk: 'risk' },
  },
  it: {
    notFound: '(non trovato)', where: (path, status) => `Sei in: ${path} (${status})`,
    lost: id => `Sei in: ${id} (nodo non trovato nel grafo)`, idle: 'Sei in: nessun passo avviato (ariadne start <id>)', left: what => `Resta da fare: ${what ?? '(non scritto)'}`,
    next: 'Prossimo', none: 'nessuno nel piano', waiting: 'Rientri in sospeso', back: 'rientra in', noWaiting: 'Rientri in sospeso: nessuno',
    because: 'perché', loose: '## Fuori dalle milestone', replacedBy: 'sostituito da', deferredTo: 'rinviato a',
    changed: '## Decisioni sostituite e rinvii', others: '## Altre milestone',
    allSteps: 'Tutti i passi, una riga ciascuno: .ariadne/STATE.md',
    title: full => `# Stato del lavoro (${full ? 'vista generata da ariadne: non modificare a mano' : 'scheda generata da ariadne'})`,
    cut: '… (tagliata: .ariadne/STATE.md)',
    comments: '## Commenti da leggere', reply: id => `rispondi: ariadne answer ${id} "…"`,
    decisions: '## Decisioni aperte', risks: '## Rischi aperti', on: 'su', kind: { decision: 'decisione', risk: 'rischio' },
  },
})

export const CARD_LIMIT = 3500
const MAX_FILES = 4

/** The files of a node: its file proofs and the files its commits touched, outside .ariadne/. */
function filesOf(node, files) {
  const own = (node.proof ?? []).flatMap(p => (p.type === 'file' ? [showRef(p.ref)] : p.type === 'commit' ? files.get(p.ref) ?? [] : []))
  return [...new Set(own.filter(f => !f.startsWith('.ariadne/')))].sort().slice(0, MAX_FILES)
}

export function render(nodes, thread, files = new Map(), { full = false, brief = 0 } = {}) {
  const g = makeGraph(nodes)
  const current = g.get(thread.current)
  const milestoneOf = id => (g.get(id)?.kind === 'milestone' ? id : g.containers(id).find(c => g.get(c).kind === 'milestone'))
  const titled = id => `${id} ${g.get(id)?.title ?? say('notFound')}`
  const target = id => g.get(milestoneOf(id) ?? id)?.title ?? id

  const head = current
    ? [
        say('where', [...g.containers(current.id)].reverse().map(id => g.get(id).title).concat(current.title).join(' › '), current.status),
        say('left', current.detail ?? current.what),
      ]
    : [thread.current ? say('lost', thread.current) : say('idle')]
  const nextId = current ? g.next(current.id) : thread.current ? null : g.first()
  const open = nodes.filter(n => n.kind === 'detour' && (n.status === 'active' || n.status === 'todo') && n.reentry)
  head.push(`${say('next')}: ${nextId ? titled(nextId) : say('none')}`)
  head.push(open.length ? `${say('waiting')}: ${open.map(n => `${n.title} → ${say('back')} ${n.reentry}`).join(' · ')}` : say('noWaiting'))

  // brief 1: the other milestones lose their goal; brief 2: done steps keep only their title.
  // Title and what, without saying the title twice when the what begins with it (as a migrated item does).
  const body = n => (!n.what || n.what === n.title ? n.title : n.what.startsWith(n.title.replace(/…$/, '')) ? n.what : `${n.title}: ${n.what}`)
  const line = n => {
    const status = n.status === 'replaced' ? `replaced → ${titled(n.replaced_by)}` : n.status === 'deferred' ? `deferred → ${target(n.deferred_to)}` : n.status
    const head = `- ${n.id} [${isWork(n) ? status : `${say('kind')[n.kind]} ${status}`}] `
    if (brief >= 2 && n.status === 'done' && n.id !== current?.id) return head + n.title
    const f = filesOf(n, files)
    return head + body(n) + (n.why ? ` · ${say('because')}: ${n.why}` : '') + (f.length ? ` · file: ${f.join(', ')}` : '')
  }
  const milestones = nodes.filter(n => n.kind === 'milestone')
  const inside = m => nodes.filter(n => n.kind !== 'milestone' && milestoneOf(n.id) === m.id)
  // No one closes a milestone by hand: its steps tell its state.
  const state = m => {
    const steps = inside(m).filter(n => n.kind !== 'risk')
    if (steps.some(n => n.status === 'active')) return 'active'
    if (steps.length && steps.every(n => ['done', 'replaced', 'deferred'].includes(n.status))) return 'done'
    return m.status
  }
  // An open decision or risk has its own section in the card: not repeated among the steps.
  const waits = n => !isWork(n) && n.status === 'todo'
  const section = m => [`## ${m.title} (${state(m)})${m.what ? `: ${m.what}` : ''}`, ...inside(m).filter(n => full || !waits(n)).map(line)]
  const here = current ? milestoneOf(current.id) : nextId && milestoneOf(nextId)
  const blocks = [head]
  const about = n => `- ${n.id} ${body(n)}`
  const comments = nodes.flatMap(n => (n.comments ?? []).filter(c => !c.answer).map(c => `- ${n.id} ${n.title}: «${c.text}» (${say('reply', n.id)})`))
  if (comments.length) blocks.push([say('comments'), ...comments])
  const decisions = nodes.filter(n => n.kind === 'decision' && waits(n))
    .map(n => about(n) + (milestoneOf(n.id) ? ` (${g.get(milestoneOf(n.id)).title})` : ''))
  if (decisions.length) blocks.push([say('decisions'), ...decisions])
  const risks = nodes.filter(n => n.kind === 'risk' && waits(n) && (full || milestoneOf(n.id) === here))
    .map(n => `${about(n)} (${say('on')} ${titled(n.parent)})`)
  if (risks.length) blocks.push([say('risks'), ...risks])
  if (full) {
    blocks.push(...milestones.map(section))
    const loose = nodes.filter(n => n.kind !== 'milestone' && !milestoneOf(n.id))
    if (loose.length) blocks.push([say('loose'), ...loose.map(line)])
  } else {
    if (here) blocks.push(section(g.get(here)))
    const changed = nodes.filter(n => n.status === 'replaced' || n.status === 'deferred')
      .map(n => `- ${n.id} ${n.title} → ${n.status === 'replaced' ? `${say('replacedBy')} ${titled(n.replaced_by)}` : `${say('deferredTo')} ${target(n.deferred_to)}`}`)
    if (changed.length) blocks.push([say('changed'), ...changed])
    const others = milestones.filter(m => m.id !== here).map(m => `- ${m.title} (${state(m)})${brief >= 1 || !m.what ? '' : `: ${m.what}`}`)
    if (others.length) blocks.push([say('others'), ...others])
    blocks.push([say('allSteps')])
  }
  return [say('title', full), ...blocks.map(b => b.join('\n')).join('\n\n').split('\n')].join('\n')
}

/** The card for the start of a session, under CARD_LIMIT characters. */
export function card(nodes, thread, files) {
  let text = render(nodes, thread, files)
  for (let brief = 1; text.length > CARD_LIMIT && brief <= 2; brief++) text = render(nodes, thread, files, { brief })
  return text.length > CARD_LIMIT ? text.slice(0, CARD_LIMIT - 40).replace(/\n[^\n]*$/, '') + `\n${say('cut')}` : text
}

/** Every milestone in full: the file .ariadne/STATE.md. */
export const view = (nodes, thread, files) => render(nodes, thread, files, { full: true })
