import { test } from 'node:test'
import assert from 'node:assert/strict'
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, statSync, symlinkSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import { findConflicts, report } from './doctor.mjs'

// These tests read what ariadne writes in Italian; English has its own tests.
process.env.ARIADNE_LANG = 'it'

/** A home with a Claude Code configuration and a project that still lean on STATE.md, the way a real setup does. */
function setup() {
  const home = mkdtempSync(join(tmpdir(), 'ariadne-doctor-'))
  const write = (path, text) => {
    mkdirSync(join(path, '..'), { recursive: true })
    writeFileSync(path, text)
  }
  const config = join(home, '.claude')
  write(join(config, 'settings.json'), JSON.stringify({
    hooks: {
      SessionStart: [{ hooks: [{ type: 'command', command: '/usr/bin/python3 ~/.claude/scripts/guard.py state' }] }],
      PreToolUse: [{ hooks: [{ type: 'command', command: 'python3 ~/.claude/scripts/quiet.py' }] }],
    },
  }))
  write(join(config, 'scripts', 'guard.py'), 'import sys\n\n# inject the repo\'s STATE.md at session start\nprint(open("STATE.md").read())\n')
  write(join(config, 'scripts', 'quiet.py'), 'print("nothing about state here")\n')
  write(join(config, 'skills', 'handoff', 'SKILL.md'), '# handoff\n\nRewrite STATE.md and append one line to LOG.md.\n')
  write(join(config, 'skills', 'other', 'SKILL.md'), '# other\n\nNothing to see.\n')
  write(join(config, 'CLAUDE.md'), '# Rules\n\n- Project knowledge lives in `STATE.md` for Next.\n')
  write(join(config, 'rules', 'ariadne.md'), 'The view .ariadne/STATE.md is generated by ariadne.\n')
  const project = join(home, 'work', 'repo')
  write(join(project, 'AGENTS.md'), '# Agents\n\nRead STATE.md first.\n')
  write(join(project, 'STATE.md'), '# State\n\n## Next\n- ship\n')
  write(join(project, 'LOG.md'), '# Log\n')
  mkdirSync(join(project, '.ariadne'))
  return { home, config, project }
}

/** Every file under `dir` with its contents, to prove doctor writes nothing. */
function snapshot(dir) {
  const out = {}
  for (const name of readdirSync(dir, { recursive: true })) {
    const path = join(dir, name)
    if (statSync(path).isFile()) out[name] = readFileSync(path, 'utf8')
  }
  return out
}

test('doctor finds every source that still injects, writes or cites STATE.md and LOG.md, and what to change in each', () => {
  const { home, config, project } = setup()
  const { findings, rootFiles } = findConflicts({ project, configDirs: [config], home })
  const seen = findings.map(f => `${f.group} ${f.file}:${f.line}${f.via ? ` (${f.via})` : ''}`)
  assert.deepEqual(seen, [
    'hook ~/.claude/scripts/guard.py:3 (SessionStart)',
    'hook ~/.claude/scripts/guard.py:4 (SessionStart)',
    'skill ~/.claude/skills/handoff/SKILL.md:3',
    'rule ~/.claude/CLAUDE.md:3',
    'project AGENTS.md:3',
  ])
  assert.deepEqual(rootFiles, ['STATE.md', 'LOG.md'])
  const text = report({ findings, rootFiles })
  assert.match(text, /^ariadne doctor: 5 righe in 4 file parlano ancora di STATE\.md o LOG\.md \(non ho modificato niente\)\n/)
  assert.match(text, /\n- ~\/\.claude\/skills\/handoff\/SKILL\.md:3 Rewrite STATE\.md and append one line to LOG\.md\.\n/)
  for (const group of ['Hook', 'Skill', 'Regole e istruzioni', 'Progetto']) assert.match(text, new RegExp(`\\n## ${group}\\n`))
  assert.match(text, /→ /)
})

test('doctor only reads: the configuration and the project are byte for byte the same afterwards', () => {
  const { home, config, project } = setup()
  const before = snapshot(home)
  report(findConflicts({ project, configDirs: [config], home }))
  assert.deepEqual(snapshot(home), before)
})

test('a configuration listed twice, as a link and as itself, is read once', () => {
  const { home, config, project } = setup()
  const { findings } = findConflicts({ project, configDirs: [config, join(config, '.')], home })
  assert.equal(findings.filter(f => f.group === 'skill').length, 1)
})

test('with nothing left on STATE.md, doctor says so in one line', () => {
  const home = mkdtempSync(join(tmpdir(), 'ariadne-doctor-'))
  const project = join(home, 'repo')
  mkdirSync(join(project, '.ariadne'), { recursive: true })
  const result = findConflicts({ project, configDirs: [join(home, '.claude')], home })
  assert.deepEqual(result, { findings: [], rootFiles: [] })
  assert.equal(report(result), 'ariadne doctor: nessuna fonte parla più di STATE.md o LOG.md: lo stato sta solo nel grafo')
})

test('a file shows at most 3 lines, then how many more, so a long script does not drown the rest', () => {
  const { home, config, project } = setup()
  writeFileSync(join(config, 'scripts', 'guard.py'), Array.from({ length: 6 }, (_, i) => `x${i} = "STATE.md"`).join('\n'))
  const text = report(findConflicts({ project, configDirs: [config], home }))
  assert.match(text, /\n- ~\/\.claude\/scripts\/guard\.py:3 \(SessionStart\) x2 = "STATE\.md"\n  … \+3 righe in questo file\n/)
  assert.doesNotMatch(text, /guard\.py:4/)
  assert.match(text, /^ariadne doctor: 9 righe in 4 file/)
})

test('a file reached through a link shows its real path, the one to edit', () => {
  const { home, config, project } = setup()
  const profile = join(home, 'profile')
  mkdirSync(profile)
  symlinkSync(join(config, 'skills'), join(profile, 'skills'))
  const { findings } = findConflicts({ project, configDirs: [profile], home })
  assert.deepEqual(findings.filter(f => f.group === 'skill').map(f => f.file), ['~/.claude/skills/handoff/SKILL.md'])
})
